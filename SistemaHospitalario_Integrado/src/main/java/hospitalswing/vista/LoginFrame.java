    private void iniciarSesion() {
        String usuario = txtUsuario.getText().trim();
        char[] clave = txtClave.getPassword();
        try {
            if (usuario.isEmpty() || clave.length == 0) {
                lblError.setText("Ingrese usuario y contraseña.");
                return;
            }
            Sesion sesion = ServicioAutenticacion.iniciarSesion(usuario, clave);
            if (sesion == null) {
                lblError.setText("Usuario o contraseña incorrectos.");
                txtClave.setText("");
                return;
            }
            dispose();
            new AdmisionFrame(sesion).setVisible(true);
        } finally {
            Arrays.fill(clave, '\0');
        }
    }

